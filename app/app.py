"""Trend Detectives app. (App role)

Run with:  python -m streamlit run app/app.py
Reads the real results in data/processed/ (generated by src/analysis/analyze_all.py).
"""

import json
from pathlib import Path

import pandas as pd
import streamlit as st

DATA = Path(__file__).parent.parent / "data" / "processed"

st.set_page_config(page_title="Trend Detectives", layout="wide")
st.title("Trend Detectives")

catalog = json.loads((DATA / "catalog.json").read_text(encoding="utf-8"))
variable = st.selectbox(
    "1. Variable",
    list(catalog["variables"]),
    format_func=lambda v: catalog["variables"][v]["name"],
)

data = json.loads((DATA / variable / "trends.json").read_text(encoding="utf-8"))
regions = pd.DataFrame(data["regions"])

st.caption(f"{data['source']} · {data['period']['start']} to {data['period']['end']} · {data['units']}")

# Red if rising, blue if falling; faded if not significant
regions["color"] = [
    ([226, 75, 74] if s > 0 else [55, 138, 221]) + ([230] if sig else [90])
    for s, sig in zip(regions["slope_per_decade"], regions["significant"])
]

# TODO: replace with a clickable map (pydeck / folium)
st.map(regions, latitude="lat", longitude="lon", color="color", size=40000)

st.dataframe(
    regions[["name", "slope_per_decade", "ci95", "pct_change_per_decade", "p_value", "significant"]],
    width="stretch", hide_index=True,
)

region = st.selectbox("2. Region", regions["id"], format_func=lambda r: catalog["regions"][r]["name"])
series = json.loads((DATA / variable / "series" / f"{region}.json").read_text(encoding="utf-8"))
st.line_chart(pd.DataFrame({"value": series["values"]}, index=pd.to_datetime(series["dates"])))

row = regions.set_index("id").loc[region]
direction = "Rising" if row["slope_per_decade"] > 0 else "Falling"
st.metric(f"{direction} per decade", f"{row['slope_per_decade']:+.2f} {data['units']}")
if row["significant"]:
    st.success("Significant: very unlikely to be due to chance.")
else:
    st.info("Not significant: with these data we can't rule out that it's due to chance.")

